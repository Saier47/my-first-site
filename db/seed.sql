ON CONFLICT (id) DO UPDATE SET
  name        = EXCLUDED.name,
  day_of_week = EXCLUDED.day_of_week,
  start_time  = EXCLUDED.start_time,
  end_time    = EXCLUDED.end_time,
  location    = EXCLUDED.location,
  updated_at  = now();

-- 说明 ON CONFLICT ... DO UPDATE SET 里的 EXCLUDED：
--   EXCLUDED 是"这次本来想插入的那一行"。
--   所以 `name = EXCLUDED.name` 的意思是"把已有的 name 更新成这次要插的值"。
--   ⚠️ 注意：不写 updated_at 的话，重跑种子后它不会变 —— 这里显式更新它。


