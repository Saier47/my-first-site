-- =====================================================================
-- 三、执行完自己看一眼
-- ---------------------------------------------------------------------
-- 这两句是"给人看的确认语句"，跑完直接能看到结果：
-- =====================================================================

-- 课程按星期排（就是页面上「一周视图」的顺序）
SELECT day_of_week AS "星期", start_time AS "开始", end_time AS "结束", name AS "课程", location AS "地点"
  FROM courses ORDER BY day_of_week, start_time;

-- DDL 按截止日期排，顺便标出状态
SELECT due_date AS "截止日期",
       due_time AS "时刻",
       title    AS "任务",
       CASE WHEN done THEN '已完成'
            WHEN due_date < '2026-10-05' THEN '已逾期'
            ELSE '待完成' END AS "状态"
  FROM ddls ORDER BY due_date, due_time;


