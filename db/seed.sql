-- =====================================================================
-- seed.sql · 种子数据（Day 16 · 2026-10-05）
-- ---------------------------------------------------------------------
-- 这个文件回答一个问题：**空表里塞什么数据，才能验证"页面上的东西是对的"。**
--
-- 怎么用：
--   bash db/run-sql.sh seed.sql
--
-- ⚠️ 前置条件：先跑过 schema.sql（表得先存在）
--
-- ---------------------------------------------------------------------
-- 🔴 为什么要写成「可重复执行」（清单的完成标准之一）
--
-- 第一版最容易写成这样：
--     INSERT INTO courses (id, name, ...) VALUES ('c_01', '高等数学', ...);
--
-- 这种写法跑第二遍会**报主键冲突**（c_01 已经存在了）。
-- 于是你每次想重置数据，都得先手动清空 —— 麻烦，而且容易忘。
--
-- 正确姿势：**ON CONFLICT (id) DO UPDATE**
--     "如果这个 id 已经有了，就更新它；没有就插入。"
--   → 跑第一遍：插入 10 行
--   → 跑第二遍：还是 10 行（原地更新，不新增、不报错）
--   → 跑第 N 遍：结果永远一样 ← **这叫"幂等"（idempotent）**
--
-- 「幂等」不是什么高级词，就是"**同样的操作做几遍，结果都一样**"。
-- 数据库的初始化脚本、部署脚本，全都该是幂等的。
--
-- ---------------------------------------------------------------------
-- 🔴 为什么种子数据要"故意设计得刁钻"
--
-- 种子数据不是为了"看着好看"，是为了**把边界情况顶出来**。
-- 下面这几条是故意的，每条都在测一个真实的坑：
--
--   · day_of_week 覆盖 1 和 7（周一、周日）—— 测边界
--   · 同一天有 2 门课 —— 测"同一天要显示多门课"
--   · DDL 有 done = true 的 —— 测"已完成的和没完成的分开显示"
--   · DDL 有 due_time = '' 的 —— 测"不写具体几点"的情况
--   · DDL 日期有过去的、有将来的 —— 测"逾期区"和"即将到期"
--   · 课程名用真实的中文名 —— 测 UTF-8 编码没坏
-- =====================================================================


