/* /api/health —— HTTP 云函数（Day 15）
 * ===================================================================
 * 这个函数只有一个职责：**回答"服务还活着吗"**。
 *
 * 为什么第一个云函数要做这个？
 *   前 14 天，网页的数据都存在用户自己的浏览器里 —— "服务在不在"
 *   这个问题根本不存在（本地跑的东西不会不在）。
 *   从今天起，数据要放到一台**别人的电脑**（云上）上，
 *   于是冒出一个新问题：**我怎么知道那台电脑是活的？**
 *   /api/health 就是这个问题的答案 —— 行业里叫「健康检查」（health check）。
 *
 * 它为什么必须存在（三个真实用途）：
 *   1. 部署完立刻知道成没成 —— 不用去点页面，敲一行 curl 就知道
 *   2. 以后网页打不开时，第一步就是访问它 —— 能分开"是网络断了"还是"是云挂了"
 *   3. 上线后监控系统定时来敲它 —— 敲不通就告警
 *
 * 它故意做得**很笨**：不读数据库、不调别的服务、不碰用户数据。
 *   因为健康检查自己不能有病 —— 如果它依赖数据库，那数据库一慢，
 *   你看到的是"服务挂了"，其实是"数据库慢了"，反而更难查。
 *
 * -------------------------------------------------------------------
 * ⚠️ 这一版和「普通云函数」的区别（Day 15 踩过的坑）
 *
 * 云函数有两种类型，**部署后类型不能改**，所以第一版就得选对：
 *
 *   ① 事件型（Event）—— 腾讯云帮你调用 main()，把返回值当结果。
 *      **没有公网网址**。只能被"别的程序"调用（比如小程序里调它）。
 *
 *   ② HTTP 型 —— 你自己起一个网页服务器（node 的 http 模块），
 *      监听 9000 端口。腾讯云给你一个网址，浏览器能直接打开。
 *
 * 今天要的是"公网能访问的 JSON 接口" → **必须选 ②**。
 * 所以这个文件不是导出一个 main() 函数，而是**真的开了一个服务器**。
 * =================================================================== */

'use strict';

// Node 自带的 HTTP 服务器模块 —— 不用装任何东西
const http = require('http');

// ⚠️ 端口必须写 9000。这不是"随便挑一个"，是腾讯云 SCF 平台**规定**的：
//    它会来这个端口找你起的服务。写成别的端口，平台找不到你，就报"启动失败"。
const PORT = 9000;

// ⚠️ 版本号。看到它就知道线上跑的是哪一次部署 —— 排查问题时很有用。
const VERSION = '0.1.0';

/**
 * 组装要返回的 JSON。
 * 抽成函数是因为"响应内容"和"怎么写回去"是两件事 ——
 * 分开写以后加字段只改这里，不用动网络那部分。
 */
function buildPayload() {
  return {
    ok: true,
    service: 'my-first-site',
    version: VERSION,

    // 时间戳用 **ISO 8601 格式**（带 Z 的那种标准写法），
    // 因为它是唯一"人读得懂、机器也读得懂、还不歧义"的写法。
    // 不用 toLocaleString() —— 那会跟着服务器所在地变，
    // 你这边看是"晚上 11 点"，服务器在别的时区可能显示"下午 3 点"。
    time: new Date().toISOString(),

    // 顺手回报运行时版本：将来函数报错，第一件事就是确认它到底跑在哪个 Node 上。
    runtime: `node ${process.version}`,
  };
}

const server = http.createServer((req, res) => {
  // 健康检查只认 GET。别的请求（POST/DELETE）明确拒绝 ——
  // 免得有人拿它当"万能接口"往里塞东西。
  if (req.method !== 'GET') {
    res.writeHead(405, { 'Content-Type': 'application/json; charset=utf-8' });
    res.end(JSON.stringify({ ok: false, error: 'Method Not Allowed' }));
    return;
  }

  res.writeHead(200, {
    'Content-Type': 'application/json; charset=utf-8',
    // 不许缓存 —— 健康检查的意义就是"此刻"的状态，缓存了就等于骗人。
    'Cache-Control': 'no-store',
  });
  res.end(JSON.stringify(buildPayload()));
});

server.listen(PORT, () => {
  // 这行会写进云端日志。部署后如果访问不通，
  // 第一件事就是去看日志里有没有这句话 —— 有，说明服务起来了。
  console.log(`[api-health] listening on http://0.0.0.0:${PORT}`);
});
